let LANG = 'tr';

function setLang(code) { LANG = I18N[code] ? code : 'en'; }

function t(key, vars) {
  const table = I18N[LANG] || I18N.en;
  let s = table[key];
  if (s === undefined) s = (I18N.en[key] !== undefined ? I18N.en[key] : key);
  if (vars) {
    Object.keys(vars).forEach(k => { s = s.split('{' + k + '}').join(vars[k]); });
  }
  return s;
}

/* Isletim sistemi dilini algila; desteklenmiyorsa English'e dus */
function detectLang() {
  const raw = (navigator.language || 'en').toLowerCase();
  const hit = LANGS.find(l => raw === l.code || raw.indexOf(l.code + '-') === 0);
  return hit ? hit.code : 'en';
}
